import streamlit as st
import pandas as pd
import json
import base64

def generate_report_markdown():
    if 'baseline_metrics' not in st.session_state or 'opt_metrics' not in st.session_state:
        return None
        
    baseline_all = st.session_state['baseline_metrics']
    opt_all = st.session_state['opt_metrics']

    # Find recommended model
    recommended_model = None
    max_eff = -1
    for model_name, metrics in opt_all.items():
        if metrics['eff_score'] > max_eff:
            max_eff = metrics['eff_score']
            recommended_model = model_name

    report = f"# OptiMind Studio – Optimization Report\n\n"
    
    if recommended_model:
        report += f"## 🏆 Executive Recommendation\n**{recommended_model}** is the recommended architecture, achieving the highest efficiency score of **{max_eff:.2f}**.\n\n---\n"
    
    for model, opt in opt_all.items():
        if model not in baseline_all:
            continue
            
        base = baseline_all[model]
        best_params = st.session_state['opt_best_params'][model]
        
        eff_improvement = (opt['eff_score'] - base['eff_score']) / base['eff_score'] * 100
        acc_improvement = (opt['test_acc'] - base['test_acc']) / base['test_acc'] * 100
        
        # Overfitting check
        gap = opt['train_acc'] - opt['test_acc']
        if gap > 0.05:
            overfit_status = f"High Risk (Gap: {gap*100:.1f}%)"
        elif gap < -0.05:
            overfit_status = f"Underfitting (Gap: {gap*100:.1f}%)"
        else:
            overfit_status = f"Stable (Gap: {gap*100:.1f}%)"

        report += f"## Model Architecture: {model}\n"
        report += f"**Optimization Results:**\n"
        report += f"- Efficiency Score changed by **{eff_improvement:+.2f}%**\n"
        report += f"- Test Accuracy changed by **{acc_improvement:+.2f}%**\n"
        report += f"- Generalization Status: **{overfit_status}**\n\n"
        
        report += f"### Baseline Statistics\n"
        report += f"- **Test Accuracy:** {base['test_acc']:.4f}\n"
        report += f"- **Training Time:** {base['training_time']:.4f} s\n"
        report += f"- **Efficiency Score:** {base['eff_score']:.2f}\n\n"

        report += f"### Optimized Statistics\n"
        report += f"- **Test Accuracy:** {opt['test_acc']:.4f}\n"
        report += f"- **Training Time:** {opt['training_time']:.4f} s\n"
        report += f"- **Efficiency Score:** {opt['eff_score']:.2f}\n\n"

        report += f"### Optimal Hyperparameters Found\n"
        report += f"```json\n{json.dumps(best_params, indent=4)}\n```\n\n---\n"
        
    report += "*Generated by OptiMind Studio – A Performance-Aware ML Optimization Platform*"
    return report

def render_tracker():
    st.header("📄 Report Generator")
    
    report_md = generate_report_markdown()
    if not report_md:
        st.info("Complete the Baseline Training and Optimization phases (select at least one model) to generate an automatic report.")
        return

    st.markdown("### Preview Optimization Report")
    
    # Render inside a scrollable container for cleanliness if it's long
    with st.container(height=500):
        st.markdown(report_md)
    
    b64 = base64.b64encode(report_md.encode()).decode()
    href = f'<a href="data:file/markdown;base64,{b64}" download="optimind_report.md" class="button">📥 Download Report (Markdown)</a>'
    
    st.markdown("<br>", unsafe_allow_html=True)
    st.markdown(href, unsafe_allow_html=True)
    
    # Custom CSS for the download button simulation
    st.markdown("""
        <style>
        .button {
            display: inline-block;
            padding: 0.5em 1em;
            text-decoration: none;
            background-color: #FF4B4B;
            color: white;
            border-radius: 4px;
            font-weight: bold;
        }
        .button:hover {
            background-color: #FF3333;
            color: white;
            text-decoration: none;
        }
        </style>
    """, unsafe_allow_html=True)
